/* «Mening lug'atim» va so'z taklifi — server sinovi.  Ishlatish: node tools/lugatim.js */
const { ishgaTushir, sqliteD1 } = require('./emul.js');
let xato = 0;
const ok = (n, v) => { if (!v) xato++; console.log((v ? '  ✓ ' : '  ✗ ') + n); };
(async () => {
  const BAZA = sqliteD1();
  const s = await ishgaTushir({ env: { BAZA, KABINET_PAROL: 'Bosh-Parol-2026' } });
  const U = s.url;
  const yoz = (y, b, t) => fetch(U + 'api/' + y, { method: 'POST', headers: Object.assign({ 'Content-Type': 'application/json' }, t ? { Authorization: 'Bearer ' + t } : {}), body: JSON.stringify(b) }).then(async r => Object.assign(await r.json(), { _s: r.status }));
  const ol = (y, t) => fetch(U + 'api/' + y, { headers: t ? { Authorization: 'Bearer ' + t } : {} }).then(r => r.json());
  const AT = (await yoz('g/kirish', { login: 'admin', parol: 'Bosh-Parol-2026' })).token;
  const db = BAZA._db;
  console.log('Mening lug‘atim (zaxira):');
  let d = await ol('g/lugatim?tel=901000001');
  ok('boshida bo‘sh', d.ok && d.sozlar.length === 0 && d.vaqt === 0);
  const sz = [{ id: 'a1', ar: 'قَلَمٌ', uz: 'qalam', kop: 'أَقْلَامٌ' }, { id: 'a2', ar: 'بَيْتٌ', uz: 'uy' }, { id: '', ar: 'x', uz: 'y' }, { id: 'a4', ar: '', uz: 'bo‘sh' }];
  const T1 = Date.now() - 5000;
  d = await yoz('g/lugatim', { tel: '901000001', sozlar: sz, vaqt: T1 });
  ok('saqlandi — bo‘sh va id’siz so‘zlar tashlab yuborildi', d.ok && d.saqlandi === 2);
  d = await ol('g/lugatim?tel=901000001');
  ok('boshqa qurilmada ham chiqadi', d.sozlar.length === 2 && d.sozlar[0].kop === 'أَقْلَامٌ' && d.vaqt === T1);
  d = await yoz('g/lugatim', { tel: '901000001', sozlar: [], vaqt: T1 - 1000 });
  ok('eskiroq nusxa yangisini o‘chirib yubormaydi', d.eski && d.sozlar.length === 2);
  ok('boshqa raqamniki alohida', (await ol('g/lugatim?tel=901000002')).sozlar.length === 0);
  ok('raqamsiz — rad', !(await yoz('g/lugatim', { sozlar: sz })).ok);
  d = await yoz('g/lugatim', { tel: '901000001', sozlar: Array.from({ length: 1500 }, (_, i) => ({ id: 'k' + i, ar: 'ك' + i, uz: 's' + i })), vaqt: Date.now() });
  ok('1000 tadan ortig‘i saqlanmaydi', d.saqlandi === 1000);
  console.log('So‘z taklifi:');
  const tk = (b) => yoz('g/soz-taklif', Object.assign({ tel: '901000001', ism: 'Ali Valiyev' }, b));
  ok('lotin harfida yozilgan «arabcha» rad etiladi', !(await tk({ ar: 'kitab', uz: 'kitob' })).ok);
  ok('tarjimasiz rad etiladi', !(await tk({ ar: 'مِظَلَّةٌ', uz: '' })).ok);
  ok('raqamsiz rad etiladi', !(await yoz('g/soz-taklif', { ar: 'مِظَلَّةٌ', uz: 'soyabon' })).ok);
  d = await tk({ ar: 'مِظَلَّةٌ', uz: 'soyabon', kop: 'مِظَلَّاتٌ', qism: 3, izoh: 'darsda uchradi' });
  ok('taklif yuborildi', d.ok && d.id > 0);
  ok('adminga Telegram: «Yangi so‘z taklifi»', s.telegram.some(m => /Yangi so‘z taklifi/.test(m.text || '') && /soyabon/.test(m.text) && /Ali Valiyev/.test(m.text)));
  d = await tk({ ar: 'مِظَلَّةٌ', uz: 'soyabon, zontik' });
  ok('shu so‘z yana yuborilsa — ikkinchi nusxa emas, yangilanadi', d.ok && d.yangilandi && db.prepare('SELECT COUNT(*) AS n FROM soz_taklif').get().n === 1);
  await tk({ ar: 'حَاسُوبٌ', uz: 'kompyuter' });
  d = await ol('g/soz-takliflarim?tel=901000001');
  ok('foydalanuvchiga: 2 ta taklifi «kutilmoqda»', d.ok && d.takliflar.length === 2 && d.takliflar.every(x => x.holat === 'kutilmoqda'));
  ok('admin bo‘lmagan ro‘yxatni ko‘ra olmaydi', !(await ol('g/soz-takliflar')).ok);
  ok('admin bo‘lmagan hal qila olmaydi', !(await yoz('g/soz-taklif-hal', { id: 1, amal: 'qabul', qism: 1 })).ok);
  ok('kabinetda kutilayotgan takliflar soni', (await ol('g/kabinet', AT)).kutilgan.soz === 2);
  d = await ol('g/soz-takliflar', AT);
  const t1 = d.takliflar.find(x => x.uz.startsWith('soyabon')), t2 = d.takliflar.find(x => x.uz === 'kompyuter');
  ok('admin: ro‘yxat — kim, qachon, qaysi qism', d.ok && d.takliflar.length === 2 && t1.ism === 'Ali Valiyev' && t1.tel === '+998901000001');
  ok('qism tanlanmasa qabul qilinmaydi', !(await yoz('g/soz-taklif-hal', { id: t2.id, amal: 'qabul' }, AT)).ok);
  d = await yoz('g/soz-taklif-hal', { id: t1.id, amal: 'qabul', uz: 'soyabon', qism: 2 }, AT);
  const y = (await ol('lugat')).yamoq;
  ok('qabul — umumiy lug‘atga qo‘shildi (tuzatilgan tarjima, 2-qism)', d.ok && y.qosh.length === 1 && y.qosh[0].ar === 'مِظَلَّةٌ' && y.qosh[0].uz === 'soyabon' && y.qosh[0].qism === 2 && y.qosh[0].kop === 'مِظَلَّاتٌ' && y.v === 1);
  ok('ikkinchi marta hal qilib bo‘lmaydi', !(await yoz('g/soz-taklif-hal', { id: t1.id, amal: 'rad' }, AT)).ok);
  d = await yoz('g/soz-taklif-hal', { id: t2.id, amal: 'rad', javob: 'lug‘atda bor' }, AT);
  ok('rad — lug‘atga qo‘shilmadi', d.ok && (await ol('lugat')).yamoq.qosh.length === 1);
  d = await ol('g/soz-takliflarim?tel=901000001');
  ok('foydalanuvchiga holat: biri qabul, biri rad (sababi bilan)', d.takliflar.find(x => x.id === t1.id).holat === 'qabul' && d.takliflar.find(x => x.id === t2.id).javob === 'lug‘atda bor');
  ok('kutilayotganlar 0 ga tushdi', (await ol('g/kabinet', AT)).kutilgan.soz === 0 && (await ol('g/soz-takliflar', AT)).takliflar.length === 0);
  ok('«hammasi» — tarix ko‘rinadi', (await ol('g/soz-takliflar?hammasi=1', AT)).takliflar.length === 2);
  for (let i = 0; i < 30; i++) await yoz('g/soz-taklif', { tel: '901000009', ar: 'كلمة' + i, uz: 'soz ' + i });
  ok('bir kishi 30 tadan ortiq kutilayotgan taklif yubora olmaydi', (await yoz('g/soz-taklif', { tel: '901000009', ar: 'زائد', uz: 'ortiqcha' }))._s === 429);
  s.close();
  console.log(xato ? '\n' + xato + ' ta xato' : '\nhammasi joyida');
  process.exit(xato ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
